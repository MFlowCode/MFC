#!/usr/bin/env python3
"""Exact viscous rates of the manufactured fields of run_mms.py (needs sympy); writes exact_rates.py.

Cylindrical (x, r, th), tau = mu (grad u + grad u^T) + (mu_b - 2 mu/3) (div u) I:
  f_x = d tau_xx/dx + (1/r) d(r tau_rx)/dr + (1/r) d tau_thx/dth
  f_r = d tau_xr/dx + (1/r) d(r tau_rr)/dr + (1/r) d tau_thr/dth - tau_thth/r
  f_th = d tau_xth/dx + (1/r) d(r tau_rth)/dr + (1/r) d tau_thth/dth + tau_rth/r
  W   = div(tau . u)
MASTER gives the rates of the operator before #1910 was fixed: in 3D the theta divergence and the hoop terms lack
1/r; in 2D the stress is the Cartesian (x, r) one (div u without u_r/r) and there is no hoop term.
"""

import os

import sympy as sp

x, r, th = sp.symbols("x r th", real=True)
A, mu, mub = sp.symbols("A mu mub", positive=True)
R = 2


def rates(ux, ur, ut, dim3=True, master=False):
    d = sp.diff
    cart2 = master and not dim3
    exx, err = d(ux, x), d(ur, r)
    ett = (d(ut, th) / r if dim3 else 0) + ur / r
    exr = (d(ux, r) + d(ur, x)) / 2
    ext = ((d(ux, th) / r if dim3 else 0) + d(ut, x)) / 2
    ert = (r * d(ut / r, r) + (d(ur, th) / r if dim3 else 0)) / 2
    div = exx + err if cart2 else exx + err + ett
    lam = mub - sp.Rational(2, 3) * mu
    t = {("x", "x"): 2 * mu * exx + lam * div, ("r", "r"): 2 * mu * err + lam * div, ("t", "t"): 2 * mu * ett + lam * div, ("x", "r"): 2 * mu * exr, ("x", "t"): 2 * mu * ext, ("r", "t"): 2 * mu * ert}

    def T(a, b):
        return t[(a, b)] if (a, b) in t else t[(b, a)]

    s = 1 if master else 1 / r

    def dth(f):
        return d(f, th) * s if dim3 else 0

    hoop_tt = 0 if cart2 else T("t", "t") * (s if dim3 else 1 / r)
    fx = d(T("x", "x"), x) + d(r * T("r", "x"), r) / r + dth(T("t", "x"))
    fr = d(T("x", "r"), x) + d(r * T("r", "r"), r) / r + dth(T("t", "r")) - hoop_tt
    ft = d(T("x", "t"), x) + d(r * T("r", "t"), r) / r + dth(T("t", "t")) + T("r", "t") * s
    u = {"x": ux, "r": ur, "t": ut}
    q = {a: sum(T(a, b) * u[b] for b in "xrt") for a in "xrt"}
    W = d(q["x"], x) + d(r * q["r"], r) / r + dth(q["t"])
    return [sp.simplify(e) for e in (fx, fr, ft, W)]


CASES = {
    "A3": (A * (r / R) ** 2 * sp.cos(th), 0 * r, 0 * r, True),  # the #1910 case: exact d(rho u_x)/dt = 3 mu A cos(th)/R^2
    "B3": (0 * r, 0 * r, A * (r + sp.Rational(1, 2) / r), True),  # Taylor-Couette: zero viscous force
    "C3": (A * r**3 * sp.cos(th), A * r**2 * sp.cos(th), -A * r**2 * sp.sin(th) + A * r**3, True),  # all components
    "E2": (A * (r / R) ** 2, A * (r / R) ** 3, 0 * r, False),  # 2D axisymmetric, radial flow (hoop)
}

if __name__ == "__main__":
    out = ['"""Generated by derive_rates.py: manufactured fields and exact (and pre-fix) viscous rates."""', "", "from numpy import cos, sin  # noqa: F401", "", "FIELDS, RATES, MASTER = {}, {}, {}"]

    def f(e):
        return sp.pycode(e).replace("math.", "") + " + 0 * r * th"

    for k, (ux, ur, ut, d3) in CASES.items():
        out.append(f"FIELDS['{k}'] = lambda r, th, A: ({f(ux)}, {f(ur)}, {f(ut)})")
        out.append(f"RATES['{k}'] = lambda r, th, A, mu, mub: ({', '.join(f(e) for e in rates(ux, ur, ut, d3))})")
        out.append(f"MASTER['{k}'] = lambda r, th, A, mu, mub: ({', '.join(f(e) for e in rates(ux, ur, ut, d3, master=True))})")
    open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "exact_rates.py"), "w").write("\n".join(out) + "\n")
